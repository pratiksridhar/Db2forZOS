-- Varied QA schema exemplar for Db2 13 for z/OS (design status; never executed by
-- this repository). Purpose: show how a small domain schema spreads clause
-- variants across objects so DDL extraction meets many distinct catalog states.
-- It passes `python3 tools/ddl.py lint` and the `core` variety baseline of
-- `python3 tools/ddl.py coverage --baseline core`.
--
-- Environment assumptions (record real values in a profile before execution):
-- APPLCOMPAT V13R1M500 or higher, CURRENT RULES DB2, existing storage group
-- SYSDEFLT, active 4 KB pool BP0, authority to create the database and objects.
-- Every PRIMARY KEY/UNIQUE in an explicit table space gets its enforcing unique
-- index (same columns, same order) before any child table references it.

SET CURRENT RULES = 'DB2';

CREATE DATABASE QAVDB01
  STOGROUP SYSDEFLT
  BUFFERPOOL BP0
  INDEXBP BP0
  CCSID EBCDIC;

-- PBG, EBCDIC, explicit options; no SEGSIZE so DPSEGSZ supplies the default.
CREATE TABLESPACE QAVS01 IN QAVDB01
  MAXPARTITIONS 8
  DSSIZE 1 G
  BUFFERPOOL BP0
  LOCKSIZE ROW
  LOCKMAX 1000
  CLOSE NO
  COMPRESS YES
  FREEPAGE 10
  PCTFREE 15 FOR UPDATE 10
  MAXROWS 100
  TRACKMOD NO
  USING STOGROUP SYSDEFLT PRIQTY -1 SECQTY -1;

CREATE TABLE QAV.CUSTOMER
  (CUSTOMER_ID INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY
     (START WITH 1000, INCREMENT BY 1, CACHE 50),
   CUSTOMER_CODE CHAR(10) NOT NULL,
   DISPLAY_NAME VARCHAR(120) NOT NULL,
   STATUS CHAR(1) NOT NULL WITH DEFAULT 'A',
   CREDIT_LIMIT DECIMAL(15, 2) NOT NULL WITH DEFAULT,
   RISK_SCORE REAL,
   TAX_REF VARCHAR(32),
   CREATED_BY VARCHAR(128) NOT NULL WITH DEFAULT USER,
   CHANGED_TS TIMESTAMP NOT NULL
     GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP,
   AUDIT_NOTE VARCHAR(200) IMPLICITLY HIDDEN,
   CONSTRAINT CUSTOMER_PK PRIMARY KEY (CUSTOMER_ID),
   CONSTRAINT CUSTOMER_UK UNIQUE (CUSTOMER_CODE),
   CONSTRAINT CUSTOMER_CK CHECK (STATUS IN ('A', 'I', 'S')))
  IN QAVDB01.QAVS01
  AUDIT ALL
  DATA CAPTURE CHANGES
  APPEND NO
  NOT VOLATILE CARDINALITY;

CREATE UNIQUE INDEX QAV.CUSTOMER_PKIX
  ON QAV.CUSTOMER (CUSTOMER_ID ASC)
  CLUSTER
  FREEPAGE 0
  PCTFREE 10;

CREATE UNIQUE INDEX QAV.CUSTOMER_UKIX
  ON QAV.CUSTOMER (CUSTOMER_CODE)
  INCLUDE (STATUS)
  NOT CLUSTER;

CREATE UNIQUE WHERE NOT NULL INDEX QAV.CUSTOMER_TAXIX
  ON QAV.CUSTOMER (TAX_REF)
  NOT PADDED;

-- PBG, Unicode, SEGSIZE 4, member cluster; holds graphic and binary types.
CREATE TABLESPACE QAVS02 IN QAVDB01
  MAXPARTITIONS 2
  DSSIZE 4 G
  SEGSIZE 4
  CCSID UNICODE
  LOCKSIZE PAGE
  MEMBER CLUSTER;

CREATE TABLE QAV.PRODUCT
  (PRODUCT_ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
   SKU VARCHAR(40) NOT NULL,
   LOCAL_NAME VARGRAPHIC(60) NOT NULL,
   SHORT_CODE GRAPHIC(4),
   BARCODE BINARY(16),
   THUMB_HASH VARBINARY(64),
   LIST_PRICE DECFLOAT(34),
   WEIGHT_KG DOUBLE,
   RELEASED DATE,
   OWNER_ID VARCHAR(128) WITH DEFAULT CURRENT SQLID,
   NOTE VARCHAR(100) DEFAULT NULL,
   CONSTRAINT PRODUCT_PK PRIMARY KEY (PRODUCT_ID),
   CONSTRAINT PRODUCT_SKU_UK UNIQUE (SKU))
  IN QAVDB01.QAVS02
  AUDIT CHANGES
  APPEND YES
  VOLATILE CARDINALITY;

CREATE UNIQUE INDEX QAV.PRODUCT_PKIX ON QAV.PRODUCT (PRODUCT_ID);

CREATE UNIQUE INDEX QAV.PRODUCT_SKUIX
  ON QAV.PRODUCT (SKU DESC)
  PADDED
  FREEPAGE 31
  PCTFREE 0;

-- PBR with relative page numbering and partition-level overrides.
CREATE TABLESPACE QAVS03 IN QAVDB01
  NUMPARTS 3
  (PARTITION 1 FREEPAGE 5 PCTFREE 20,
   PARTITION 3 COMPRESS YES TRACKMOD YES)
  PAGENUM RELATIVE
  DSSIZE 4 G
  SEGSIZE 64
  LOCKSIZE ANY;

-- Two foreign keys to the same parent must share one delete rule that is not
-- SET NULL (CREATE TABLE), so SET NULL lives on PRODUCT_DOC below.
CREATE TABLE QAV.SALES_ORDER
  (ORDER_ID BIGINT NOT NULL,
   ORDER_DATE DATE NOT NULL,
   CUSTOMER_ID INTEGER NOT NULL,
   CUSTOMER_CODE CHAR(10),
   CHANNEL CHAR(3) NOT NULL WITH DEFAULT 'WEB',
   ORDER_TOTAL DECIMAL(17, 2) NOT NULL,
   PLACED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
   PICK_TIME TIME,
   CONSTRAINT ORDER_PK PRIMARY KEY (ORDER_ID),
   CONSTRAINT ORDER_CUSTOMER_FK FOREIGN KEY (CUSTOMER_ID)
     REFERENCES QAV.CUSTOMER (CUSTOMER_ID) ON DELETE RESTRICT,
   CONSTRAINT ORDER_CODE_FK FOREIGN KEY (CUSTOMER_CODE)
     REFERENCES QAV.CUSTOMER (CUSTOMER_CODE) ON DELETE RESTRICT,
   CONSTRAINT ORDER_TOTAL_CK CHECK (ORDER_TOTAL >= 0))
  IN QAVDB01.QAVS03
  PARTITION BY RANGE (ORDER_DATE)
   (PARTITION 1 ENDING AT ('2024-12-31'),
    PARTITION 2 ENDING AT ('2025-12-31'),
    PARTITION 3 ENDING AT (MAXVALUE))
  DATA CAPTURE NONE;

CREATE UNIQUE INDEX QAV.ORDER_PKIX ON QAV.SALES_ORDER (ORDER_ID);

CREATE INDEX QAV.ORDER_DATEIX
  ON QAV.SALES_ORDER (ORDER_DATE, CUSTOMER_ID)
  PARTITIONED
  CLUSTER;

CREATE INDEX QAV.ORDER_CUSTIX ON QAV.SALES_ORDER (CUSTOMER_ID DESC);

-- Explicit PBG child with a composite, unenforced foreign key.
CREATE TABLESPACE QAVS04 IN QAVDB01
  SEGSIZE 32
  LOCKSIZE ROW
  LOCKMAX SYSTEM
  COMPRESS NO
  CLOSE YES;

CREATE TABLE QAV.ORDER_LINE
  (ORDER_ID BIGINT NOT NULL,
   LINE_NO SMALLINT NOT NULL,
   PRODUCT_ID BIGINT NOT NULL REFERENCES QAV.PRODUCT (PRODUCT_ID)
     ON DELETE CASCADE,
   QTY INTEGER NOT NULL,
   PARENT_ORDER_ID BIGINT,
   PARENT_LINE_NO SMALLINT,
   CONSTRAINT LINE_PK PRIMARY KEY (ORDER_ID, LINE_NO),
   CONSTRAINT LINE_ORDER_FK FOREIGN KEY (ORDER_ID)
     REFERENCES QAV.SALES_ORDER (ORDER_ID) NOT ENFORCED,
   CONSTRAINT LINE_QTY_CK CHECK (QTY > 0))
  IN QAVDB01.QAVS04
  AUDIT NONE;

CREATE UNIQUE INDEX QAV.LINE_PKIX ON QAV.ORDER_LINE (ORDER_ID, LINE_NO);

-- A table cannot reference itself in CREATE TABLE; add the self-reference now.
-- A self-reference must use ON DELETE CASCADE or NO ACTION (ALTER TABLE).
ALTER TABLE QAV.ORDER_LINE
  ADD CONSTRAINT LINE_PARENT_FK FOREIGN KEY (PARENT_ORDER_ID, PARENT_LINE_NO)
  REFERENCES QAV.ORDER_LINE (ORDER_ID, LINE_NO) ON DELETE NO ACTION;

-- Implicit table space in the database: Db2 creates the base space, the
-- enforcing index, the hidden ROWID and the LOB space/auxiliary objects.
CREATE TABLE QAV.PRODUCT_DOC
  (DOC_ID INTEGER NOT NULL,
   PRODUCT_ID BIGINT,
   BODY CLOB(1M),
   CONSTRAINT DOC_PK PRIMARY KEY (DOC_ID),
   CONSTRAINT DOC_PRODUCT_FK FOREIGN KEY (PRODUCT_ID)
     REFERENCES QAV.PRODUCT (PRODUCT_ID) ON DELETE SET NULL)
  IN DATABASE QAVDB01;

COMMIT;
