-- BUSINESS CONTRACTS
-- DECIMAL(19,4) stores monetary amounts; rates are fractions in [0,1]. Currency
-- minor-unit rounding is an application rule. No implicit currency conversion.
-- Dates use [start,end) intervals. Business timestamps must be supplied in UTC;
-- WITH DEFAULT timestamps reflect the subsystem clock, so confirm it is UTC or
